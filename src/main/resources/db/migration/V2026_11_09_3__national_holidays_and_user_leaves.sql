CREATE TABLE public.national_holidays (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    holiday_date date NOT NULL UNIQUE,
    name character varying(120) NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.user_leaves (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.users(id),
    start_date date NOT NULL,
    end_date date NOT NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT user_leaves_date_range_check CHECK (end_date >= start_date)
);

CREATE INDEX idx_user_leaves_user_date_range
    ON public.user_leaves (user_id, start_date, end_date);

-- national_holidays menandai Libur untuk semua pengguna. user_leaves menandai
-- Cuti bagi satu pengguna ketika log_date berada di antara start_date dan end_date.
-- Kedua kondisi tersebut dikecualikan dari pembentukan status TERLEWAT.
