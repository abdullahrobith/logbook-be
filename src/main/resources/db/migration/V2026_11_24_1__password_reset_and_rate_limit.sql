-- Token reset kata sandi dan state rate limit sebelumnya hanya ada di memori.
-- Keduanya dipindahkan ke database agar tetap konsisten saat restart dan saat
-- aplikasi berjalan dalam beberapa instance.

CREATE TABLE IF NOT EXISTS public.password_reset_tokens (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id bigint NOT NULL REFERENCES public.users(id) ON DELETE CASCADE,
    token_hash character varying(64) NOT NULL UNIQUE,
    expires_at timestamp with time zone NOT NULL,
    used_at timestamp with time zone NULL,
    created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_user_id
    ON public.password_reset_tokens (user_id);

CREATE TABLE IF NOT EXISTS public.rate_limit_attempts (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bucket_key character varying(255) NOT NULL UNIQUE,
    window_started_at timestamp with time zone NOT NULL,
    failed_count integer NOT NULL DEFAULT 0,
    locked_until timestamp with time zone NULL
);
