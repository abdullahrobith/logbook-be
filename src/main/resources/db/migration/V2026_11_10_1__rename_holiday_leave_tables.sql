-- Menyesuaikan nama tabel libur dan cuti agar lebih ringkas:
--   national_holidays -> holidays
--   user_leaves       -> leaves
--
-- Constraint, index, dan sequence ikut di-rename agar konsisten. Migrasi ini
-- aman untuk database lama (masih memakai nama lama) maupun database baru yang
-- sudah memakai nama baru dari logbook.sql.

DO $$
DECLARE
    old_holidays_exists boolean := to_regclass('public.national_holidays') IS NOT NULL;
    new_holidays_exists boolean := to_regclass('public.holidays') IS NOT NULL;
    old_leaves_exists   boolean := to_regclass('public.user_leaves') IS NOT NULL;
    new_leaves_exists   boolean := to_regclass('public.leaves') IS NOT NULL;
BEGIN
    -- ========================= holidays =========================
    IF new_holidays_exists AND NOT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'holidays'
          AND column_name IN ('holiday_date', 'name')
        GROUP BY table_schema, table_name
        HAVING COUNT(*) = 2
    ) THEN
        RAISE EXCEPTION
            'Tabel public.holidays sudah ada dengan struktur berbeda. '
            'Hapus atau sesuaikan tabel tersebut sebelum migrasi dijalankan.';
    END IF;

    IF old_holidays_exists AND new_holidays_exists THEN
        -- Tabel baru sudah ada (mis. dari logbook.sql terbaru). Pindahkan data
        -- lama yang belum ada, lalu hapus tabel lama.
        INSERT INTO public.holidays (holiday_date, name)
        SELECT old.holiday_date, old.name
        FROM public.national_holidays old
        WHERE NOT EXISTS (
            SELECT 1
            FROM public.holidays current
            WHERE current.holiday_date = old.holiday_date
        );

        DROP TABLE public.national_holidays;
    ELSIF old_holidays_exists THEN
        ALTER TABLE public.national_holidays RENAME TO holidays;
        new_holidays_exists := true;
    END IF;

    IF NOT new_holidays_exists THEN
        CREATE TABLE public.holidays (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            holiday_date date NOT NULL UNIQUE,
            name character varying(120) NOT NULL,
            created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
        );
    END IF;

    IF EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'public.holidays'::regclass
          AND conname = 'national_holidays_pkey'
    ) THEN
        ALTER TABLE public.holidays
            RENAME CONSTRAINT national_holidays_pkey TO holidays_pkey;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'public.holidays'::regclass
          AND conname = 'national_holidays_holiday_date_key'
    ) THEN
        ALTER TABLE public.holidays
            RENAME CONSTRAINT national_holidays_holiday_date_key
            TO holidays_holiday_date_key;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM pg_class
        WHERE relkind = 'S'
          AND relnamespace = 'public'::regnamespace
          AND relname = 'national_holidays_id_seq'
    ) THEN
        ALTER SEQUENCE public.national_holidays_id_seq RENAME TO holidays_id_seq;
    END IF;

    -- ========================== leaves ==========================
    IF new_leaves_exists AND NOT EXISTS (
        SELECT 1
        FROM information_schema.columns
        WHERE table_schema = 'public'
          AND table_name = 'leaves'
          AND column_name IN ('user_id', 'start_date', 'end_date')
        GROUP BY table_schema, table_name
        HAVING COUNT(*) = 3
    ) THEN
        RAISE EXCEPTION
            'Tabel public.leaves sudah ada dengan struktur berbeda. '
            'Hapus atau sesuaikan tabel tersebut sebelum migrasi dijalankan.';
    END IF;

    IF old_leaves_exists AND new_leaves_exists THEN
        INSERT INTO public.leaves (user_id, start_date, end_date)
        SELECT old.user_id, old.start_date, old.end_date
        FROM public.user_leaves old
        WHERE NOT EXISTS (
            SELECT 1
            FROM public.leaves current
            WHERE current.user_id = old.user_id
              AND current.start_date = old.start_date
              AND current.end_date = old.end_date
        );

        DROP TABLE public.user_leaves;
    ELSIF old_leaves_exists THEN
        ALTER TABLE public.user_leaves RENAME TO leaves;
        new_leaves_exists := true;
    END IF;

    IF NOT new_leaves_exists THEN
        CREATE TABLE public.leaves (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id bigint NOT NULL REFERENCES public.users(id),
            start_date date NOT NULL,
            end_date date NOT NULL,
            created_at timestamp with time zone NOT NULL DEFAULT CURRENT_TIMESTAMP,
            CONSTRAINT leaves_date_range_check CHECK (end_date >= start_date)
        );
    END IF;

    IF EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'public.leaves'::regclass
          AND conname = 'user_leaves_pkey'
    ) THEN
        ALTER TABLE public.leaves
            RENAME CONSTRAINT user_leaves_pkey TO leaves_pkey;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'public.leaves'::regclass
          AND conname = 'user_leaves_user_id_fkey'
    ) THEN
        ALTER TABLE public.leaves
            RENAME CONSTRAINT user_leaves_user_id_fkey TO leaves_user_id_fkey;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'public.leaves'::regclass
          AND conname = 'user_leaves_date_range_check'
    ) THEN
        ALTER TABLE public.leaves
            RENAME CONSTRAINT user_leaves_date_range_check
            TO leaves_date_range_check;
    END IF;

    IF to_regclass('public.idx_user_leaves_user_date_range') IS NOT NULL THEN
        ALTER INDEX public.idx_user_leaves_user_date_range
            RENAME TO idx_leaves_user_date_range;
    END IF;

    IF EXISTS (
        SELECT 1
        FROM pg_class
        WHERE relkind = 'S'
          AND relnamespace = 'public'::regnamespace
          AND relname = 'user_leaves_id_seq'
    ) THEN
        ALTER SEQUENCE public.user_leaves_id_seq RENAME TO leaves_id_seq;
    END IF;

    -- Pastikan foreign key, validasi rentang, dan index tetap ada pada tabel
    -- hasil rename (termasuk bila tabel tujuan sebelumnya dibuat manual).
    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'public.leaves'::regclass
          AND conname = 'leaves_user_id_fkey'
    ) THEN
        ALTER TABLE public.leaves
            ADD CONSTRAINT leaves_user_id_fkey
            FOREIGN KEY (user_id) REFERENCES public.users(id);
    END IF;

    IF NOT EXISTS (
        SELECT 1
        FROM pg_constraint
        WHERE conrelid = 'public.leaves'::regclass
          AND conname = 'leaves_date_range_check'
    ) THEN
        ALTER TABLE public.leaves
            ADD CONSTRAINT leaves_date_range_check
            CHECK (end_date >= start_date);
    END IF;

    IF to_regclass('public.idx_leaves_user_date_range') IS NULL THEN
        CREATE INDEX idx_leaves_user_date_range
            ON public.leaves (user_id, start_date, end_date);
    END IF;
END
$$;
